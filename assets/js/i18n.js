function detectInitialLang() {
  try {
    const fromUrl = new URLSearchParams(location.search).get('lang');
    if (SUPPORTED.includes(fromUrl)) return fromUrl;
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) return saved;
  } catch (e) { /* storage bloqueado */ }
  return (navigator.language || 'pt').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

let current = detectInitialLang();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!SUPPORTED.includes(lang) || lang === current) return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignora */ }
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

export function locale() {
  return current === 'pt' ? 'pt-BR' : 'en-US';
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.pt[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

// Contagem: t('items.count', ...) / 'items.count1'
export function tCount(base, n) {
  return n === 1 && STRINGS[current][base + '1'] ? t(base + '1') : t(base, { n });
}

// Campo bilíngue de um dado: pick(item, 'name') -> item.name_pt | item.name_en
export function pick(obj, field) {
  if (!obj) return '';
  const other = current === 'pt' ? 'en' : 'pt';
  return obj[`${field}_${current}`] || obj[`${field}_${other}`] || obj[field] || '';
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-alt]').forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
}

